"""Regenerate tiny deterministic image fixtures (requires Pillow)."""
import base64
import io
import json
from pathlib import Path
from PIL import Image, ImageDraw

images = {}
def save(name, image, fmt, **kwargs):
    stream = io.BytesIO()
    image.save(stream, format=fmt, **kwargs)
    mime = {'PNG':'png', 'JPEG':'jpeg', 'WEBP':'webp', 'GIF':'gif'}[fmt]
    images[name] = 'data:image/' + mime + ';base64,' + base64.b64encode(stream.getvalue()).decode()

landscape = Image.new('RGB', (200,100))
draw = ImageDraw.Draw(landscape)
draw.rectangle((0,0,49,99),fill=(240,40,40))
draw.rectangle((50,0,149,99),fill=(40,200,60))
draw.rectangle((150,0,199,99),fill=(40,80,240))
save('png',landscape,'PNG')
save('jpeg',landscape,'JPEG',quality=95,subsampling=0)
save('webp',landscape,'WEBP',lossless=True)
save('portrait',landscape.transpose(Image.Transpose.ROTATE_90),'PNG')
save('alpha',Image.new('RGBA',(40,40),(240,40,40,128)),'PNG')
frames=[Image.new('RGB',(40,40),color) for color in [(240,40,40),(40,80,240)]]
save('gif',frames[0],'GIF',save_all=True,append_images=frames[1:],duration=[150,150],loop=0)
save('animatedWebp',frames[0],'WEBP',save_all=True,append_images=frames[1:],duration=[150,150],loop=0,lossless=True)
save('apng',frames[0],'PNG',save_all=True,append_images=frames[1:],duration=[150,150],loop=0)
# Local palettes, partial rectangles, transparency and disposal 2/3.
moving=[]
for x,color in [(0,(240,40,40,255)),(8,(40,200,60,255)),(16,(40,80,240,255)),(24,(230,180,40,255))]:
    frame=Image.new('RGBA',(40,30),(0,0,0,0))
    ImageDraw.Draw(frame).rectangle((x,5,x+9,14),fill=color)
    moving.append(frame)
save('gifPatches',moving[0],'GIF',save_all=True,append_images=moving[1:],duration=[80,120,160,200],loop=0,disposal=[1,2,3,1],optimize=True)
save('webpPatches',moving[0],'WEBP',save_all=True,append_images=moving[1:],duration=[80,120,160,200],loop=0,lossless=True)
images['broken']='data:image/png;base64,aW52YWxpZA=='
output=Path(__file__).parent/'app/src/image-fixtures.ts'
output.write_text('// Generated by platform/wasm/generate-image-fixtures.py.\nexport const images = '+json.dumps(images,indent=2)+';\n')
print(output)
